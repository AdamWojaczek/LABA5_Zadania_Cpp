#include "CLifeCell.h"

//---------------------------------------------------------------------------------------------------------------------

CLifeCell::CLifeCell(bool alive)
    : m_alive(alive)
{
}

//---------------------------------------------------------------------------------------------------------------------

bool CLifeCell::IsAlive() const
{
    return m_alive;
}

//---------------------------------------------------------------------------------------------------------------------

void CLifeCell::SetAlive()
{
    m_alive = true;
}

//---------------------------------------------------------------------------------------------------------------------

void CLifeCell::SetDead()
{
    m_alive = false;
}

